/** 把已画好的精灵再整体放大 k 倍（宠物要比角色大一倍） */
function scaleUp(canvas, k) {
  const out = document.createElement('canvas');
  out.width = Math.round(canvas.width * k);
  out.height = Math.round(canvas.height * k);
  const g = out.getContext('2d');
  g.imageSmoothingEnabled = true;
  g.drawImage(canvas, 0, 0, out.width, out.height);
  return out;
}

/**
 * 给精灵叠一层纯色（受击闪白 / 中毒变绿等）。
 * 结果按 "精灵引用 + 颜色 + 透明度档位" 缓存，避免每帧新建 canvas。
 */
const tintCache = new Map();
export function tintSprite(spr, key, color, alphaStep) {
  const step = Math.max(0, Math.min(4, Math.round(alphaStep)));
  const ck = `${key}|${color}|${step}`;
  if (tintCache.has(ck)) return tintCache.get(ck);

  const c = document.createElement('canvas');
  c.width = spr.width;
  c.height = spr.height;
  const g = c.getContext('2d');
  g.drawImage(spr, 0, 0);
  g.globalCompositeOperation = 'source-atop';
  g.globalAlpha = step / 4;
  g.fillStyle = color;
  g.fillRect(0, 0, c.width, c.height);

  if (tintCache.size > 120) tintCache.clear();
  tintCache.set(ck, c);
  return c;
}

/** 左右翻转（角色朝不同方向时用） */
function flipH(canvas) {
  const out = document.createElement('canvas');
  out.width = canvas.width;
  out.height = canvas.height;
  const g = out.getContext('2d');
  g.translate(out.width, 0);
  g.scale(-1, 1);
  g.drawImage(canvas, 0, 0);
  return out;
}

