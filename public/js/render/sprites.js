/**
 * Low-Poly 程序化精灵：多边形 + 平面着色 → 离屏 canvas。
 * 零外部图片依赖，永不裂图。
 *
 * 和旧版（字符矩阵像素画）的区别：
 *   - 旧版一个字符 = 一个像素，锐利但颗粒感重；
 *   - 新版用**多边形拼块 + 每块两档明暗**（受光面 / 背光面），做出 low-poly 的"切面感"。
 *
 * 对外 API 完全不变（返回的仍是离屏 canvas），所以 canvas.js / hud.js 一行都不用改。
 *
 * 尺寸约定：sprite 的逻辑尺寸用"单位"描述（1 单位 = 旧版 1 像素 = U 个真实像素），
 * 所以世界里的实际大小和旧版完全一致，不会因为换风格突然变大变小。
 */

/**
 * 每个逻辑单位多少真实像素。
 * 3 是旧版基准；先乘 1.5 对齐 tile 的放大（那边 64→96），再乘 1.5 是因为
 * "人物还是太小"—— 传奇类游戏里角色本来就比一格 tile 高得多，压在一格里反而显小。
 * 宠物倍率见 Sprites.pet（改成 1.4×，人物变大后 2× 会占满半屏）。
 */
const U = 6.75;

// ------------------------------------------------------------------ 基础图元

/** 颜色明暗：amt>0 提亮、<0 压暗（-1~1） */
function shade(hex, amt) {
  const n = parseInt(hex.slice(1), 16);
  let r = (n >> 16) & 255;
  let g = (n >> 8) & 255;
  let b = n & 255;
  if (amt >= 0) {
    r += (255 - r) * amt; g += (255 - g) * amt; b += (255 - b) * amt;
  } else {
    r *= 1 + amt; g *= 1 + amt; b *= 1 + amt;
  }
  return `rgb(${r | 0},${g | 0},${b | 0})`;
}

/**
 * 画一个多边形。
 * @param {number[][]} pts [[x,y],...] 单位坐标
 * @param {string} fill 填充色
 * @param {boolean|string} edge 是否描边（默认淡淡的暗边，加强"切面"感）；传 '' 关闭
 */
function poly(g, pts, fill, edge) {
  g.beginPath();
  g.moveTo(pts[0][0], pts[0][1]);
  for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
  g.closePath();
  g.fillStyle = fill;
  g.fill();
  if (edge !== '') {
    g.strokeStyle = edge || 'rgba(10,10,20,0.22)';
    g.lineWidth = 0.13;
    g.stroke();
  }
}

/** 椭圆（眼睛 / 高光用） */
function dot(g, x, y, rx, ry, fill) {
  g.fillStyle = fill;
  g.beginPath();
  g.ellipse(x, y, rx, ry, 0, 0, Math.PI * 2);
  g.fill();
}

/** 建一块画布：wU/hU 是逻辑单位，内部坐标系缩放到单位坐标，绘制函数直接用单位坐标画 */
function makePoly(wU, hU, drawFn) {
  const c = document.createElement('canvas');
  c.width = wU * U;
  c.height = hU * U;
  const g = c.getContext('2d');
  g.scale(U, U);
  g.lineJoin = 'round';
  drawFn(g);
  return c;
}

