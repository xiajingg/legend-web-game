// ------------------------------------------------------------------ 构建 + 缓存

const cache = new Map();
function get(key, factory) {
  if (!cache.has(key)) cache.set(key, factory());
  return cache.get(key);
}

// 各精灵的逻辑尺寸（单位）。宽 16 是约定，高度按角色需要。
const DIM = {
  hero: [16, 19], slime: [16, 12], wolf: [16, 12], skeleton: [16, 16],
  orc: [16, 19], boar: [16, 13], boss: [16, 19], pet: [16, 15],
};

/** 怪物 / 主角的绘制函数表：key → [idle绘制, 逻辑尺寸] */
const MODELS = {
  hero: drawHero,
  slime: drawSlime,
  wolf: drawWolf,
  skeleton: drawSkeleton,
  orc: drawOrc,
  boar: drawBoar,
  boss: drawBoss,
  pet: drawPet,
};

function spriteOf(key, atk) {
  const draw = MODELS[key];
  const [w, h] = DIM[key];
  return get(`${key}${atk ? 'A' : ''}`, () => makePoly(w, h, (g) => draw(g, atk)));
}

